"""Generate the typed Bhash bindings and route contract for this starter."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
TUTORIAL = ROOT.parents[1] / "tutorial/typed-api"
HEADER = "// SPDX-License-Identifier: Apache-2.0\n// Generated by generate.py from schema.json.\n"
TYPES = {"string": "पाठ", "integer": "पूर्णांक", "boolean": "तार्किक"}
BOUNDS = {"string": ("minLength", "maxLength"), "integer": ("minimum", "maximum"), "boolean": ()}
STATUSES = {
    200: "OK", 201: "Created", 400: "Invalid request", 404: "Task not found",
    409: "Task ID already exists", 415: "Expected application/json",
    422: "Request does not match the schema", 500: "Internal error",
}
ASCII_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
BHASH_NAME = re.compile(r"[\u0904-\u0939][\u0900-\u097f_]*")
ROUTE = re.compile(r"/(?:[A-Za-z0-9_-]+|:[A-Za-z_][A-Za-z0-9_]*)(?:/(?:[A-Za-z0-9_-]+|:[A-Za-z_][A-Za-z0-9_]*))*")


def literal(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def unique(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError(f"duplicate JSON key: {key}")
        value[key] = item
    return value


def name(pattern, value):
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise ValueError(f"invalid name or path: {value!r}")
    return value


def schema_ref(key):
    return {"$ref": f"#/components/schemas/{key}"}


def content(schema):
    return {"application/json": {"schema": schema}}


def record_source(record, schema):
    bhash_name = name(BHASH_NAME, record["name"])
    fields = record["fields"]
    properties, member_names, definitions, checks, serializations = {}, set(), [], [], []
    for field in fields:
        key = name(ASCII_NAME, field["key"])
        member = name(BHASH_NAME, field["name"])
        kind = field["type"]
        bounds = BOUNDS[kind]
        if key in properties or member in member_names or set(field) != {"key", "name", "type", *bounds}:
            raise ValueError(f"invalid or duplicate field: {field}")
        numbers = [field[bound] for bound in bounds]
        if numbers and (any(type(n) is not int for n in numbers) or
                        not -(2**31) <= numbers[0] <= numbers[1] < 2**31 or
                        (kind == "string" and numbers[0] < 0)):
            raise ValueError(f"invalid bounds: {field}")
        member_names.add(member)
        properties[key] = {"type": kind, **dict(zip(bounds, numbers))}
        if kind == "string":
            properties[key]["pattern"] = r"^[^\u0000]*$"
        bhash_type = TYPES[kind]
        definitions.append(f"{member}: {bhash_type}")
        args = [f"क्षेत्रलो(वस्तु,{literal(key)})", literal(key), *map(str, numbers)]
        checks.append(f"    स्थिर {member}: {bhash_type} = {bhash_type}जाँचो({', '.join(args)});")
        serializations.append(f"    फल[{literal(key)}] = मानक.{member};")
    if not fields or len(fields) > 16:
        raise ValueError("records need between 1 and 16 fields")
    schema.update(type="object", additionalProperties=False, required=list(properties), properties=properties)
    members = ", ".join(f["name"] for f in fields)
    return [
        f"सार्वजनिक अभिलेख {bhash_name}({', '.join(definitions)});", "",
        f"सार्वजनिक फलन {bhash_name}पढ़ो(मूल: सर्ववस्तु) -> {bhash_name} {{",
        f"    स्थिर वस्तु: मानचित्र<पाठ,सर्ववस्तु> = वस्तुजाँचो(मूल,{len(fields)});",
        *checks, f"    लौटाओ नया {bhash_name}({members});", "}", "",
        f"सार्वजनिक फलन {bhash_name}लिखो(मानक: {bhash_name}) -> मानचित्र<पाठ,सर्ववस्तु> {{",
        "    स्थिर फल: मानचित्र<पाठ,सर्ववस्तु> = नया मानचित्र<पाठ,सर्ववस्तु>();",
        *serializations, "    लौटाओ फल;", "}", "",
    ]


def route_source(routes, schemas):
    paths, handlers, operations, registrations, helpers = {}, [], set(), [], []
    for route in routes:
        method, status = route["method"], route["status"]
        path = name(ROUTE, route["path"])
        handler = name(BHASH_NAME, route["handler"])
        operation = name(ASCII_NAME, route["operation"])
        if method not in {"GET", "POST", "PUT", "PATCH", "DELETE"} or status not in (200, 201):
            raise ValueError(f"unsupported method or success status: {route}")
        if handler in handlers or operation in operations:
            raise ValueError(f"duplicate route handler or operation: {route}")
        handlers.append(handler)
        operations.add(operation)
        parameters = re.findall(r":([A-Za-z_][A-Za-z0-9_]*)", path)
        mappings = route.get("parameters", {})
        if len(set(parameters)) != len(parameters) or set(parameters) != set(mappings):
            raise ValueError(f"path parameter bindings must match the route: {path}")
        parameters_doc = []
        for index, parameter in enumerate(parameters, 1):
            record, field = mappings[parameter].split(".")
            bounds = schemas[record]["properties"][field]
            if bounds["type"] != "integer" or bounds["minimum"] < 0:
                raise ValueError("starter path parameters require bounded nonnegative integers")
            parameters_doc.append({"name": parameter, "in": "path", "required": True, "schema": bounds})
            helpers.extend([
                f"फलन {handler}पथ_{index}(अनुरोध: वेबअनुरोध) -> पूर्णांक {{",
                f'    स्थिर फल: पूर्णांक = वेब.संख्या(अनुरोध.पथमान["{parameter}"],{bounds["maximum"]});',
                f'    यदि (फल < {bounds["minimum"]}) {{ फेंको नया वेबत्रुटि(४००,"पथ मान सीमा से बाहर है।"); }}',
                "    लौटाओ फल;", "}", "",
            ])
        openapi_path = re.sub(r":([A-Za-z_][A-Za-z0-9_]*)", r"{\1}", path)
        methods = paths.setdefault(openapi_path, {})
        if method.lower() in methods or route["response"] not in schemas:
            raise ValueError(f"duplicate route or unknown response record: {route}")
        responses = {str(status): {"description": STATUSES[status], "content": content(schema_ref(route["response"]))}}
        for code in route["errors"]:
            if code < 400 or code not in STATUSES:
                raise ValueError(f"unsupported error status: {code}")
            responses[str(code)] = {"description": STATUSES[code], "content": content(schema_ref("Error"))}
        info = {"operationId": operation, "responses": responses}
        if parameters_doc:
            info["parameters"] = parameters_doc
        if "request" in route:
            request = route["request"]
            if request not in schemas:
                raise ValueError(f"unknown request record: {request}")
            info["requestBody"] = {"required": True, "content": content(schema_ref(request))}
        methods[method.lower()] = info
        registrations.append(f"    अनुप्रयोग.जोड़ो({literal(method)},{literal(path)},{handler});")
        helpers.extend([f"फलन {handler}स्थिति() -> पूर्णांक {{ लौटाओ {status}; }}", ""])
    args = ", ".join(["अनुप्रयोग: वेबअनुप्रयोग", *(f"{h}: वेबचालक" for h in handlers)])
    code = [
        HEADER.rstrip(), "संकुल कार्यसेवा;",
        "आयात मानक.वेब; आयात मानक.वेबचालक; आयात मानक.वेबअनुप्रयोग;",
        "आयात मानक.वेबअनुरोध; आयात मानक.वेबत्रुटि;", "",
        f"फलन मार्गजोड़ो({args}) -> शून्य {{", *registrations, "}", "", *helpers,
    ]
    return paths, "\n".join(code)


def generate(source):
    schemas, records = {}, []
    for key, record in source["records"].items():
        name(ASCII_NAME, key)
        if key == "Error":
            raise ValueError("Error is reserved for HTTP errors")
        schemas[key] = {}
        records.extend(record_source(record, schemas[key]))
    paths, routes = route_source(source["routes"], schemas)
    paths["/openapi.json"] = {"get": {"operationId": "getOpenApi",
                                      "responses": {"200": {"description": "OpenAPI document",
                                                            "content": content({"type": "object"})}}}}
    schemas["Error"] = {
        "type": "object", "required": ["error", "status"],
        "properties": {"error": {"type": "string"}, "status": {"type": "integer"}},
    }
    document = {"openapi": "3.0.3", "info": {"title": source["title"], "version": source["version"]},
                "paths": paths, "components": {"schemas": schemas}}
    json_text = json.dumps(document, ensure_ascii=False, indent=2) + "\n"
    model_code = "\n".join(records)
    records.extend([f"सार्वजनिक फलन खुलाविवरण() -> पाठ {{ लौटाओ {literal(literal(document))}; }}", ""])
    validation = (ROOT / "contract/src/validation.bhash").read_text(encoding="utf-8").splitlines()
    example = (ROOT / "model-demo/src/main.bhash").read_text(encoding="utf-8").splitlines()
    standalone = [*(line for line in example if line.startswith("आयात मानक.")),
                  *validation[2:], "", *model_code.splitlines(),
                  *(line for line in example[1:] if not line.startswith("आयात "))]
    return {
        ROOT / "contract/src/generated.bhash": HEADER + "संकुल कार्यअनुबंध;\n\n" + "\n".join(records),
        ROOT / "service/src/routes.bhash": routes,
        ROOT / "openapi.json": json_text,
        TUTORIAL / "models.bhash": HEADER + "\n".join(standalone).rstrip() + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files need updating")
    args = parser.parse_args()
    source = json.loads((ROOT / "schema.json").read_text(encoding="utf-8"), object_pairs_hook=unique)
    for path, contents in generate(source).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != contents:
                parser.error(f"{path} is stale. Run generate.py.")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
