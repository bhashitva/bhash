#!/usr/bin/env python3
"""Generate the reviewed Bhash identifier profile from pinned Unicode 18.0 data."""
import argparse
import hashlib
import json
import re
import unicodedata
from pathlib import Path

from audit_unicode_identifiers import BASE, FILES, ROOT, properties, records


def ranges(points):
    result = []
    for point in sorted(points):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def escape(point):
    return f"\\u{point:04X}" if point <= 0xFFFF else f"\\u{{{point:X}}}"


def pattern(points):
    return "[" + "".join(escape(a) + ("-" + escape(b) if b != a else "") for a, b in ranges(points)) + "]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = args.data_dir
    for filename in FILES:
        text = (data / filename).read_text(encoding="utf8")
        if filename != "UnicodeData.txt" and "18.0.0" not in text[:2500]:
            raise ValueError("Expected Unicode 18.0.0 in " + filename)
    chars = {}
    for line in (data / "UnicodeData.txt").read_text(encoding="utf8").splitlines():
        fields = line.split(";")
        chars[int(fields[0], 16)] = fields
    core = properties(data / "DerivedCoreProperties.txt",
                      {"XID_Start", "XID_Continue", "Default_Ignorable_Code_Point"})
    deva = properties(data / "Scripts.txt", {"Devanagari"})["Devanagari"]
    for points, fields in records(data / "ScriptExtensions.txt"):
        deva.difference_update(points)
        if "Deva" in fields[0].split():
            deva.update(points)
    excluded = core["Default_Ignorable_Code_Point"] | properties(data / "PropList.txt", {"Bidi_Control"})["Bidi_Control"]
    start = (core["XID_Start"] & deva) - excluded
    follow = {p for p in (core["XID_Continue"] & deva) - excluded if chars[p][2][0] in "LM"}
    follow.update(range(0x30, 0x3A))
    follow.update(range(0x966, 0x970))
    follow.update((0x5F, 0x953, 0x954))
    assert len(start) == 102 and len(follow) == 205 and start <= follow
    for point in follow:
        # Host normalization is usable only when its decomposition/CCC data agrees
        # with the pinned inputs. New inert letters have empty decomposition and CCC 0.
        assert unicodedata.decomposition(chr(point)) == chars[point][5]
        assert unicodedata.combining(chr(point)) == int(chars[point][3])
    normalization = hashlib.sha256()
    for first in sorted(follow):
        for second in sorted(follow):
            normalization.update(unicodedata.normalize('NFC', chr(first) + chr(second)).encode('utf8') + b'\0')
    metadata = {
        "profile": "bhash-devanagari-1", "unicode": "18.0.0", "source": BASE,
        "start": ranges(start), "continue": ranges(follow), "contextual": [0x200C, 0x200D],
        "continuationExceptions": [0x953, 0x954],
        "nfcPairsSha256": normalization.hexdigest(),
        "inputs": {name: hashlib.sha256((data / name).read_bytes()).hexdigest() for name in FILES},
    }
    def java_ranges(points):
        return ", ".join(f"0x{x:X}" for pair in ranges(points) for x in pair)
    java = '''// Generated by scripts/generate_identifier_profile.py from Unicode 18.0.0.
// Unicode data license https://www.unicode.org/license.txt
package dev.bhash.frontend;

public final class IdentifierProfile {
    private IdentifierProfile() {}
    public static final String VERSION = "bhash-devanagari-1 / Unicode 18.0.0";
    private static final int[] START = {%s};
    private static final int[] CONTINUE = {%s};
    private static boolean contains(int[] ranges, int point) {
        for (int i = 0; i < ranges.length; i += 2) {
            if (point < ranges[i]) return false;
            if (point <= ranges[i + 1]) return true;
        }
        return false;
    }
    public static boolean start(int point) { return contains(START, point); }
    public static boolean part(int point) { return contains(CONTINUE, point); }
    public static boolean cursorPart(int point) {
        return part(point) || point == 0x200C || point == 0x200D
                || point >= 'A' && point <= 'Z' || point >= 'a' && point <= 'z';
    }
}
''' % (java_ranges(start), java_ranges(follow))
    watch_parts = follow | {0x200C, 0x200D}
    cursor = watch_parts | set(range(65, 91)) | set(range(97, 123))
    js = ("// Generated by scripts/generate_identifier_profile.py. Unicode 18.0.0.\n"
          "// Unicode data license https://www.unicode.org/license.txt\n"
          f"export const identifierStart = /{pattern(start)}/u;\n"
          f"export const identifierWord = /{pattern(cursor)}+/u;\n"
          "export const identifierKey = text => text.replace(/[\\u200C\\u200D]/gu, '').normalize('NFC');\n")
    python = ("# Generated by scripts/generate_identifier_profile.py. Unicode 18.0.0.\n"
              "# Unicode data license https://www.unicode.org/license.txt\n"
              f"CONTINUE = {tuple(tuple(pair) for pair in ranges(cursor))!r}\n\n"
              "def identifier_part(char):\n"
              "    point = ord(char)\n"
              "    return any(first <= point <= last for first, last in CONTINUE)\n")
    watch_path = ROOT / "editors/vscode/debug/bhash_watch.py"
    watch = watch_path.read_text(encoding="utf8")
    begin = watch.index("def _watch_letter(c):")
    end = watch.index("def _watch_digit(c):", begin)
    watch_profile = ("def _watch_letter(c):\n"
                     f"    return any(a <= ord(c) <= b for a, b in {tuple(tuple(pair) for pair in ranges(start))!r})\n\n\n"
                     "def _watch_mark(c):\n"
                     f"    return any(a <= ord(c) <= b for a, b in {tuple(tuple(pair) for pair in ranges(watch_parts))!r})\n\n\n")
    outputs = {
        "src/main/java/dev/bhash/frontend/IdentifierProfile.java": java,
        "docs/identifier-profile.json": json.dumps(metadata, indent=2) + "\n",
        "playground/src/identifier-profile.js": js,
        "editors/jupyter/bhash_jupyter/identifier_profile.py": python,
        "editors/vscode/debug/bhash_watch.py": watch[:begin] + watch_profile + watch[end:],
    }
    grammar_path = ROOT / "src/main/antlr4/Bhash.g4"
    grammar = grammar_path.read_text(encoding="utf8")
    outputs["src/main/antlr4/Bhash.g4"] = re.sub(r"fragment ID_IGNORABLE : .*? ;",
            lambda _: "fragment ID_IGNORABLE : " + pattern(excluded) + " ;", grammar)
    for filename, contents in outputs.items():
        path = ROOT / filename
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf8") != contents:
                raise SystemExit("Generated profile differs: " + filename)
        else:
            path.write_text(contents, encoding="utf8")
    print("Verified" if args.check else "Generated", "102 starts, 205 continuations, two contextual joiners")


if __name__ == "__main__":
    main()
